local Objects = {}
local BEHAVIORS = {}

local OBJ_NEXT <const> = 0x60
local OBJ_GFX <const> = 0x14
local OBJ_APPEARANCE <const> = 0xF0
local OBJ_SPAWN_OBJ <const> = 0xFC
local OBJ_SUBTYPE <const> = 0x144
local OBJ_BEHAVIOR <const> = 0x20C

local function is_valid_address(address)
	return type(address) == "number" and 0x80000000 <= address and address < 0x80800000
end

-- Returns nil instead of throwing on a bad address
local function safe_read_dword(address)
	if not is_valid_address(address) or address % 4 ~= 0 then
		return nil
	end
	local ok, value = pcall(memory.readdword, address)
	if not ok then
		return nil
	end
	return value
end

-- JP behavior scripts are shifted relative to US in the STROOP table
local function align_jp(segmented)
	if segmented >= 0x13002EA0 then return segmented + 32 end
	if segmented >= 0x13002C6C then return segmented + 36 end
	if segmented >= 0x13002998 then return segmented + 24 end
	return segmented
end

local function matches(criteria, obj)
	return (criteria.gfx == nil or criteria.gfx == obj.gfx)
		and (criteria.sub == nil or criteria.sub == obj.sub)
		and (criteria.app == nil or criteria.app == obj.app)
		and (criteria.spawn == nil or criteria.spawn == obj.spawn)
end

function Objects.get_name(address)
	local address_source = Addresses[Settings.address_source_index]
	local bankStart = (safe_read_dword(address_source.segment_table + 0x13 * 4) or 0) % 0x80000000
	local behavior = safe_read_dword(address + OBJ_BEHAVIOR)
	if behavior == nil or behavior == 0 then
		return "Uninitialized Object"
	end

	local offset = behavior % 0x80000000 - bankStart
	if offset < 0 then
		return "Unknown Object"
	end
	local segmented = 0x13000000 + offset
	if address_source.name() == Locales.str('ADDRESS_JAPAN') then
		segmented = align_jp(segmented)
	end

	local candidates = BEHAVIORS[segmented]
	if candidates == nil then
		return "Unknown Object"
	end

	local obj = {
		gfx = safe_read_dword(address + OBJ_GFX),
		sub = safe_read_dword(address + OBJ_SUBTYPE),
		app = safe_read_dword(address + OBJ_APPEARANCE),
		spawn = safe_read_dword(address + OBJ_SPAWN_OBJ),
	}
	for _, criteria in ipairs(candidates) do
		if matches(criteria, obj) then
			return criteria.name
		end
	end
	return "Unknown Object"
end

---Iterate over all loaded objects
---@param callback function(address) # takes in the address of each iterated object as an argument
function Objects.iterate(callback)
	-- The game stores 16 different lists of loaded objects.
	-- Each root node is 0x68 bytes in size
	local process_groups = Addresses[Settings.address_source_index].process_groups
	for i = 0, 15, 1 do
		local objectList = process_groups + 0x68 * i
		local currentObject = safe_read_dword(objectList + OBJ_NEXT) -- objectList->next
		local count = 0
		-- Iterate until we reach the root node again, since these lists are cyclic
		-- Note: 240 is the max number of slots
		while is_valid_address(currentObject) and currentObject ~= objectList and count < 240 do
			callback(currentObject)
			count = count + 1
			currentObject = safe_read_dword(currentObject + OBJ_NEXT) -- currentObject->next
		end
	end
end

